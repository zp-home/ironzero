"""The :class:`TerrainGrid` value type: construction, geometry and collision.

The class is a frozen ``slots`` dataclass whose behaviour is split across three
modules of this package so no single file grows past the size budget:

* ``grid.py``     — the dataclass itself: parsing, coordinate helpers, collision;
* ``passable.py`` — ``PassableMixin``: nearest-passable snapping;
* ``pathing.py``  — ``PathingMixin``: deterministic A* and path diagnostics.

Both mixins are stateless (they only read the fields declared here and call the
public helpers below), so the mixin composition is an equivalence-preserving
refactor: ``TerrainGrid(...)``, its field order, ``dataclasses.fields``,
``frozen``/``slots`` semantics and every public method keep their old
signatures and results.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Any

from .passable import PassableMixin
from .pathing import PathingMixin
from .utils import _clamp_int, _positive_int

__all__ = ["TerrainGrid"]


@dataclass(frozen=True, slots=True)
class TerrainGrid(PassableMixin, PathingMixin):
    """Immutable blocked-tile mask with world<->tile coordinate helpers."""

    map_id: str
    name: str
    width: int  # tiles
    height: int  # tiles
    tile_width: int
    tile_height: int
    width_px: int
    height_px: int
    blocked: tuple[bool, ...]  # row-major, length width*height

    # ------------------------------------------------------------------
    # Construction
    # ------------------------------------------------------------------
    @classmethod
    def from_payload(cls, payload: dict[str, Any]) -> "TerrainGrid":
        """Build a grid from the ``map.json`` payload written by the backend."""

        if isinstance(payload, TerrainGrid):
            return payload
        if not isinstance(payload, dict):
            raise ValueError("terrain payload must be a mapping")
        width = _positive_int(payload.get("width"), "width")
        height = _positive_int(payload.get("height"), "height")
        tile_width = _positive_int(payload.get("tile_width", 20), "tile_width")
        tile_height = _positive_int(payload.get("tile_height", 20), "tile_height")
        width_px = _positive_int(payload.get("width_px") or width * tile_width, "width_px")
        height_px = _positive_int(payload.get("height_px") or height * tile_height, "height_px")
        raw = payload.get("blocked")
        if raw is None:
            raise ValueError("terrain payload missing 'blocked' mask")
        values = [1 if int(value) != 0 else 0 for value in raw]
        expected = width * height
        if len(values) < expected:
            values.extend([0] * (expected - len(values)))
        elif len(values) > expected:
            values = values[:expected]
        return cls(
            map_id=str(payload.get("id") or ""),
            name=str(payload.get("name") or ""),
            width=width,
            height=height,
            tile_width=tile_width,
            tile_height=tile_height,
            width_px=width_px,
            height_px=height_px,
            blocked=tuple(bool(value) for value in values),
        )

    @classmethod
    def from_file(cls, path: str) -> "TerrainGrid":
        """Load a terrain grid from a JSON file.

        The canonical file is the platform's ``map.json`` (see the module
        docstring), but the loader is deliberately tolerant so a map generated by
        a separate script can be dropped in without a conversion step:

        * the payload may be the object itself or nested under ``terrain`` or
          ``map`` (useful when a scenario config mixes terrain + spawn data);
        * when tile counts are omitted they are derived from ``width_px`` /
          ``height_px`` and the tile size.
        """

        import json
        from pathlib import Path as _Path

        file_path = _Path(path)
        try:
            payload = json.loads(file_path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            raise FileNotFoundError(f"terrain file not found: {file_path}") from None
        if isinstance(payload, cls):
            return payload
        if not isinstance(payload, dict):
            raise ValueError(f"terrain file {file_path} must contain a JSON object")
        candidates: list[dict[str, Any]] = []
        for key in ("terrain", "map"):
            nested = payload.get(key)
            if isinstance(nested, dict) and ("blocked" in nested or "blocked_mask" in nested):
                candidates.append(nested)
        if "blocked" in payload or "blocked_mask" in payload:
            candidates.append(payload)
        if not candidates:
            raise ValueError(
                f"terrain file {file_path} has no 'blocked' mask (looked at top level, "
                "'terrain' and 'map')"
            )
        merged = dict(candidates[0])
        # Fill geometry from the outer object when the nested one omits it.
        for key in ("id", "name", "width", "height", "tile_width", "tile_height",
                    "width_px", "height_px"):
            if merged.get(key) is None and payload.get(key) is not None:
                merged[key] = payload[key]
        if "blocked" not in merged and "blocked_mask" in merged:
            merged["blocked"] = merged["blocked_mask"]
        if merged.get("width") is None or merged.get("height") is None:
            width_px = merged.get("width_px")
            height_px = merged.get("height_px")
            tile_width = int(merged.get("tile_width", 20) or 20)
            tile_height = int(merged.get("tile_height", 20) or 20)
            if width_px is not None and height_px is not None and width_px and height_px:
                merged.setdefault("width", max(1, int(round(int(width_px) / tile_width))))
                merged.setdefault("height", max(1, int(round(int(height_px) / tile_height))))
        return cls.from_payload(merged)

    # ------------------------------------------------------------------
    # Basic properties
    # ------------------------------------------------------------------
    @property
    def tile_count(self) -> int:
        return self.width * self.height

    @property
    def land_ratio(self) -> float:
        if not self.blocked:
            return 0.0
        return 1.0 - (sum(1 for value in self.blocked if value) / len(self.blocked))

    # ------------------------------------------------------------------
    # Coordinate helpers
    # ------------------------------------------------------------------
    def world_to_tile(self, x: float, y: float) -> tuple[int, int]:
        """World (pixel) point -> tile indices, clamped into the map."""

        tx = int(math.floor(x / self.tile_width))
        ty = int(math.floor(y / self.tile_height))
        return (
            _clamp_int(tx, 0, self.width - 1),
            _clamp_int(ty, 0, self.height - 1),
        )

    def _tile_unclamped(self, x: float, y: float) -> tuple[int, int]:
        return (
            int(math.floor(x / self.tile_width)),
            int(math.floor(y / self.tile_height)),
        )

    def tile_center(self, tx: int, ty: int) -> tuple[float, float]:
        return (
            (tx + 0.5) * self.tile_width,
            (ty + 0.5) * self.tile_height,
        )

    # ------------------------------------------------------------------
    # Collision queries
    # ------------------------------------------------------------------
    def is_blocked_tile(self, tx: int, ty: int) -> bool:
        if tx < 0 or ty < 0 or tx >= self.width or ty >= self.height:
            return True
        return self.blocked[ty * self.width + tx]

    def is_blocked_world(self, x: float, y: float) -> bool:
        """True when the world point is outside the map or on blocked ground."""

        if not (math.isfinite(x) and math.isfinite(y)):
            return True
        tx, ty = self._tile_unclamped(x, y)
        return self.is_blocked_tile(tx, ty)
